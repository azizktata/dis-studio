/**
 * Emit `app/_lib/imageSizes.ts` — intrinsic dimensions for every portfolio
 * image.
 *
 * The gallery is a masonry: tiles keep each image's own aspect ratio instead of
 * being cropped to a fixed one. `next/image` needs real width/height to lay
 * that out without shifting, so the sizes are baked in at build time rather
 * than measured in the browser.
 *
 *   node scripts/write-image-sizes.mjs
 */

import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PUBLIC = join(ROOT, "public");

const ROOTS = [
  join(PUBLIC, "projets"),
  join(PUBLIC, "ambiance"),
  join(PUBLIC, "DIS STUDIO", "3DS MAX"),
];

/** Width/height from a JPEG's SOF marker. */
function jpegSize(buf) {
  let i = 2;
  while (i < buf.length - 9) {
    if (buf[i] !== 0xff) {
      i++;
      continue;
    }
    const marker = buf[i + 1];
    if (
      marker >= 0xc0 &&
      marker <= 0xcf &&
      marker !== 0xc4 &&
      marker !== 0xc8 &&
      marker !== 0xcc
    ) {
      return { height: buf.readUInt16BE(i + 5), width: buf.readUInt16BE(i + 7) };
    }
    if (i + 3 >= buf.length) break;
    i += 2 + buf.readUInt16BE(i + 2);
  }
  return null;
}

const walk = (dir) => {
  let out = [];
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out = out.concat(walk(p));
    else if (/\.jpe?g$/i.test(e.name)) out.push(p);
  }
  return out;
};

const entries = [];
for (const root of ROOTS) {
  try {
    statSync(root);
  } catch {
    continue;
  }
  for (const file of walk(root)) {
    const size = jpegSize(readFileSync(file));
    if (!size) continue;
    // Public URL: encoded the same way content.ts builds its paths.
    const rel = relative(PUBLIC, file).split(/[\\/]/).map(encodeURIComponent).join("/");
    entries.push([`/${rel}`, size]);
  }
}

entries.sort((a, b) => a[0].localeCompare(b[0]));

const body = entries
  .map(([k, v]) => `  ${JSON.stringify(k)}: { w: ${v.width}, h: ${v.height} },`)
  .join("\n");

const file = `/**
 * GENERATED by scripts/write-image-sizes.mjs — do not edit by hand.
 *
 * Intrinsic dimensions for portfolio images. The gallery lays tiles out as a
 * masonry, so each image needs its real aspect ratio to reserve the right space
 * before it loads.
 */

export type ImageSize = { w: number; h: number };

export const imageSizes: Record<string, ImageSize> = {
${body}
};

/** Falls back to 3:2 for anything not in the map. */
export function sizeOf(src: string): ImageSize {
  return imageSizes[src] ?? { w: 1500, h: 1000 };
}
`;

writeFileSync(join(ROOT, "app", "_lib", "imageSizes.ts"), file);
console.log(`wrote app/_lib/imageSizes.ts — ${entries.length} images`);
